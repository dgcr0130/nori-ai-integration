test('재열기 세션 대기 중 이전 내용은 숨기며 로그인 변경·실패로 비운다', async ({ page, context, backend }) => {
  await login(context, backend)
  await page.goto(backend.origin + '/a')
  await page.getByRole('button', { name: /AI.*열기/ }).click()
  await questionInput(page).fill('비공개 초안')
  await page.getByRole('button', { name: 'AI 대화 최소화' }).click()
  await login(context, backend, 'bob')
  let release!: () => void
  const held = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/ai/session', async route => { await held; await route.continue() }, { times: 1 })
  await page.getByRole('button', { name: 'AI 대화 열기' }).click()
  await expect(questionInput(page)).toHaveCount(0)
  await expect(page.locator('nori-ai-widget')).not.toContainText('비공개 초안')
  release()
  await expect(questionInput(page)).toHaveValue('')
  await page.getByRole('button', { name: 'AI 대화 최소화' }).click()
  await context.clearCookies()
  await page.getByRole('button', { name: 'AI 대화 열기' }).click()
  await expect(page.getByRole('alert')).toContainText('로그인이 필요합니다.')
  await expect(questionInput(page)).toHaveCount(0)
})

