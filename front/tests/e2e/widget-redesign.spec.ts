test('재열기 시 대화 접근 403은 이전 답변·초안·진행을 다시 노출하지 않는다', async ({ page, context, backend }) => {
  await login(context, backend)
  await page.goto(backend.origin + '/a')
  await page.getByRole('button', { name: 'AI 대화 열기' }).click()
  await questionInput(page).fill('접근 회수 전 질문')
  await page.getByRole('button', { name: '보내기', exact: true }).click()
  await expect.poll(() => backend.openStreams).toBe(1)
  const id = [...backend.jobs.keys()][0]!
  backend.event(id, 'job.completed', '2')
  await expect(page.getByRole('region', { name: '답변', exact: true })).toContainText('검증 답변')
  await questionInput(page).fill('회수 전 초안')
  await page.getByRole('button', { name: 'AI 대화 최소화' }).click()
  const conversation = backend.jobs.get(id)!.accepted.conversationId
  backend.failNext({ method: 'GET', path: new RegExp(`/conversations/${conversation}$`), status: 403,
    body: { code: 'REQUEST_FORBIDDEN', message: '대화 접근 권한이 없습니다.' } })
  await page.getByRole('button', { name: 'AI 대화 열기' }).click()
  await expect(page.getByRole('alert')).toContainText('대화 접근 권한이 없습니다.')
  await expect(page.getByRole('region', { name: '대화 내용', exact: true })).not.toContainText('검증 답변')
  await expect(questionInput(page)).toHaveValue('')
  await expect(page.getByRole('region', { name: '질문 진행', exact: true })).toHaveCount(0)
})

